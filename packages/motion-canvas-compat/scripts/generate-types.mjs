#!/usr/bin/env node
// Generates types/modules.d.ts: one ambient module declaration for each module
// that the published Motion Canvas packages expose, re-exporting the Canvas
// Commons package that replaces it. TypeScript prefers an ambient module with
// the exact name over the files in node_modules, but not a wildcard one, so
// every deep path is listed.
//
// Usage: node scripts/generate-types.mjs [motion-canvas-version]
import {execFileSync, execSync} from 'node:child_process';
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import {tmpdir} from 'node:os';
import {dirname, join, relative, sep} from 'node:path';
import {fileURLToPath} from 'node:url';

const version = process.argv[2] ?? '3.17.2';
if (!/^\d+\.\d+\.\d+$/.test(version)) {
  throw new Error(`Expected a version like 3.17.2, got ${version}.`);
}
const outputFile = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'types',
  'modules.d.ts',
);

const packages = [
  {name: '@motion-canvas/core', target: '@canvas-commons/core'},
  {name: '@motion-canvas/2d', target: '@canvas-commons/2d'},
];

// Modules whose replacement is not the root of the package.
const redirects = {
  '@motion-canvas/2d/lib/jsx-runtime': '@canvas-commons/2d/jsx-runtime',
  '@motion-canvas/2d/lib/jsx-dev-runtime': '@canvas-commons/2d/jsx-dev-runtime',
};

// Modules with a default export, and the root export that is the same value.
const defaultExports = {
  '@motion-canvas/core/lib/plugin/DefaultPlugin': [
    'DefaultPlugin',
    '@canvas-commons/core',
  ],
};

// Modules without a Canvas Commons equivalent get no declaration.
const unsupported = new Set(['@motion-canvas/2d/lib/components/CodeBlock']);

function listDeclarationFiles(directory) {
  return readdirSync(directory, {withFileTypes: true}).flatMap(entry => {
    const path = join(directory, entry.name);
    return entry.isDirectory()
      ? listDeclarationFiles(path)
      : entry.name.endsWith('.d.ts')
        ? [path]
        : [];
  });
}

function fetchPackage(name, directory) {
  const [tarball] = JSON.parse(
    execSync(
      `npm pack ${name}@${version} --json --pack-destination "${directory}"`,
      {
        encoding: 'utf8',
      },
    ),
  ).map(entry => entry.filename);
  const extracted = name.replace('/', '__');
  mkdirSync(join(directory, extracted));
  // Relative paths: GNU tar reads `C:` in an absolute path as a host name.
  execFileSync('tar', ['-xzf', tarball, '-C', extracted], {cwd: directory});
  return join(directory, extracted, 'package');
}

function modulePath(packageDirectory, file) {
  return relative(packageDirectory, file)
    .split(sep)
    .join('/')
    .replace(/\.d\.ts$/, '');
}

function moduleNames(name, packageDirectory) {
  const libDirectory = join(packageDirectory, 'lib');
  const names = new Set([name]);
  for (const file of listDeclarationFiles(libDirectory)) {
    const path = modulePath(packageDirectory, file);
    names.add(`${name}/${path}.js`);
    names.add(`${name}/${path}`);
    if (path.endsWith('/index')) {
      names.add(`${name}/${path.slice(0, -'/index'.length)}`);
    }
  }
  return [...names];
}

function withoutExtension(moduleName) {
  return moduleName.replace(/\.js$/, '');
}

function declaration(moduleName, target) {
  const key = withoutExtension(moduleName);
  const [defaultName, defaultTarget] = defaultExports[key] ?? [];
  const body = defaultName
    ? `export {${defaultName} as default} from '${defaultTarget}';`
    : `export * from '${redirects[key] ?? target}';`;
  return `declare module '${moduleName}' {\n  ${body}\n}\n`;
}

function assertDefaultExportsAreKnown(packageDirectory, name) {
  for (const file of listDeclarationFiles(join(packageDirectory, 'lib'))) {
    const path = modulePath(packageDirectory, file);
    if (
      /^\s*export default /m.test(readFileSync(file, 'utf8')) &&
      !(`${name}/${path}` in defaultExports)
    ) {
      throw new Error(
        `${name}/${path} has a default export. Add it to defaultExports.`,
      );
    }
  }
}

const workDirectory = mkdtempSync(join(tmpdir(), 'compat-types-'));
try {
  const blocks = [];
  for (const {name, target} of packages) {
    const packageDirectory = fetchPackage(name, workDirectory);
    assertDefaultExportsAreKnown(packageDirectory, name);
    for (const moduleName of moduleNames(name, packageDirectory).sort()) {
      if (!unsupported.has(withoutExtension(moduleName))) {
        blocks.push(declaration(moduleName, target));
      }
    }
  }
  writeFileSync(
    outputFile,
    `// Generated by scripts/generate-types.mjs from Motion Canvas ${version}.\n\n${blocks.join('\n')}`,
  );
  console.log(`Wrote ${blocks.length} modules to ${outputFile}`);
} finally {
  rmSync(workDirectory, {recursive: true, force: true});
}
